    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
String patientId = txtPatientId.getText().trim();
String fullName = txtFullName.getText().trim();
String age = txtAge.getText().trim();
String contact = txtContact.getText().trim();
String address = txtAddress.getText().trim();

if (patientId.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter Patient ID to update!", "Validation Error", JOptionPane.ERROR_MESSAGE);
    return;
}

try {
    java.sql.Connection con = DatabaseConnection.getInstance().getConnection();
    String sql = "UPDATE patient SET name=?, age=?, contact=?, address=? WHERE patient_id=?";
    java.sql.PreparedStatement pstm = con.prepareStatement(sql);
    pstm.setString(1, fullName);
    pstm.setInt(2, Integer.parseInt(age));
    pstm.setString(3, contact);
    pstm.setString(4, address);
    pstm.setString(5, patientId);

    int rows = pstm.executeUpdate();
    if (rows > 0) {
        JOptionPane.showMessageDialog(this, "Patient Updated Successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        btnClearActionPerformed(null);
    } else {
        JOptionPane.showMessageDialog(this, "Patient ID Not Found!", "Error", JOptionPane.ERROR_MESSAGE);
    }
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
String patientId = txtPatientId.getText().trim();

if (patientId.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter Patient ID to delete!", "Validation Error", JOptionPane.ERROR_MESSAGE);
    return;
}

int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this patient?", "Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

if (confirm == JOptionPane.YES_OPTION) {
    try {
        java.sql.Connection con = DatabaseConnection.getInstance().getConnection();
        String sql = "DELETE FROM patient WHERE patient_id = ?";
        java.sql.PreparedStatement pstm = con.prepareStatement(sql);
        pstm.setString(1, patientId);

        int rows = pstm.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Patient Deleted Successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            btnClearActionPerformed(null);
        } else {
            JOptionPane.showMessageDialog(this, "Patient ID Not Found!", "Error", JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

