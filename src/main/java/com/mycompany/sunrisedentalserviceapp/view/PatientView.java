private void loadPatientTable() {
        DefaultTableModel model = (DefaultTableModel) tblPatients.getModel();
        model.setRowCount(0);

        List<Patient> list = patientController.getAllPatients();
        for (Patient p : list) {
            model.addRow(new Object[]{
                p.getPatientId(),
                p.getName(),
                p.getAge(),
                p.getGender(),
                p.getContactNo(),
                p.getAddress()
            });
        }
    }     
   

