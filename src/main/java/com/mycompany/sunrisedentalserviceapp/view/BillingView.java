    // === SAVE BUTTON ===
    private void btnSave2ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        if (txtPatientId5.getText().trim().isEmpty() || txtPatientName5.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all required fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            String date = txtDate5.getText().trim();
            int patientId = Integer.parseInt(txtPatientId5.getText().trim());
            String patientName = txtPatientName5.getText().trim();
            String treatment = cmbTreatment2.getSelectedItem().toString();
            
            double totalAmount = txtTotalAmount.getText().trim().isEmpty() ? 0.0 : Double.parseDouble(txtTotalAmount.getText().trim());
            double paidAmount = txtPaidAmount2.getText().trim().isEmpty() ? 0.0 : Double.parseDouble(txtPaidAmount2.getText().trim());
            double balance = txtBalance2.getText().trim().isEmpty() ? 0.0 : Double.parseDouble(txtBalance2.getText().trim());
            String status = (balance <= 0) ? "Paid" : "Pending";

            Connection conn = DatabaseConnection.getInstance().getConnection();
            String sql = "INSERT INTO payment (payment_date, patient_id, patient_name, treatment_type, total_amount, paid_amount, balance, status) VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

            PreparedStatement stmt = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
            stmt.setString(1, date);
            stmt.setInt(2, patientId);
            stmt.setString(3, patientName);
            stmt.setString(4, treatment);
            stmt.setDouble(5, totalAmount);
            stmt.setDouble(6, paidAmount);
            stmt.setDouble(7, balance);
            stmt.setString(8, status);

            int rowsInserted = stmt.executeUpdate();

            if (rowsInserted > 0) {
                ResultSet rs = stmt.getGeneratedKeys();
                int generatedBillId = 0;
                if (rs.next()) {
                    generatedBillId = rs.getInt(1);
                }
                txtBillId5.setText(String.valueOf(generatedBillId));
                
                JOptionPane.showMessageDialog(this, "Bill Saved Successfully!\nBill ID: " + generatedBillId, "Success", JOptionPane.INFORMATION_MESSAGE);
                
                loadPaymentTable(); // Refresh the table
            }

            stmt.close();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for Amounts / IDs!", "Input Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }                                        

