    // === SEARCH BUTTON ===
    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {                                          
        String searchKey = txtSearch.getText().trim();
        if (searchKey.isEmpty()) {
            loadPaymentTable();
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblTransactions.getModel();
        model.setRowCount(0);

        String sql = "SELECT bill_id, patient_id, patient_name, total_amount, status FROM payment WHERE bill_id = ? OR patient_name LIKE ?";

        try {
            Connection conn = DatabaseConnection.getInstance().getConnection();
            PreparedStatement stmt = conn.prepareStatement(sql);
            
            int billIdSearch = -1;
            try {
                billIdSearch = Integer.parseInt(searchKey);
            } catch (NumberFormatException ignored) {}

            stmt.setInt(1, billIdSearch);
            stmt.setString(2, "%" + searchKey + "%");

            ResultSet rs = stmt.executeQuery();

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("bill_id"),
                    rs.getInt("patient_id"),
                    rs.getString("patient_name"),
                    rs.getDouble("total_amount"),
                    rs.getString("status")
                };
                model.addRow(row);
            }

            rs.close();
            stmt.close();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Search Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }                                         

