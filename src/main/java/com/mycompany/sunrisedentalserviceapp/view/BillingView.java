    private void loadPaymentTable() {
        DefaultTableModel model = (DefaultTableModel) tblTransactions.getModel();
        model.setRowCount(0); 

        String sql = "SELECT bill_id, patient_id, patient_name, total_amount, status FROM payment ORDER BY bill_id DESC";

        try {
            Connection conn = DatabaseConnection.getInstance().getConnection();
            PreparedStatement stmt = conn.prepareStatement(sql);
            ResultSet rs = stmt.executeQuery();

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("bill_id"),
                    rs.getInt("patient_id"),
                    rs.getString("patient_name"),
                    rs.getDouble("total_amount"),
                    rs.getString("status")
                };
                model.addRow(row);
            }

            rs.close();
            stmt.close();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading payment data: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

