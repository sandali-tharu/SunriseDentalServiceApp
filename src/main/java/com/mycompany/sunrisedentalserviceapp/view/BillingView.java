    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {                                           
        int selectedRow = tblTransactions.getSelectedRow();
        
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a transaction from the table to delete!", "Selection Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int billId = (int) tblTransactions.getValueAt(selectedRow, 0);

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete Bill ID: " + billId + "?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            
        if (confirm == JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM payment WHERE bill_id = ?";
            try {
                Connection conn = DatabaseConnection.getInstance().getConnection();
                PreparedStatement stmt = conn.prepareStatement(sql);
                stmt.setInt(1, billId);

                int rowsDeleted = stmt.executeUpdate();
                stmt.close();

                if (rowsDeleted > 0) {
                    JOptionPane.showMessageDialog(this, "Record Deleted Successfully!", "Deleted", JOptionPane.INFORMATION_MESSAGE);
                    loadPaymentTable();
                }
            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Delete Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }                                         

